-- Ejecutar una sola vez en Supabase > SQL Editor.
-- Esta versión NO usa login de usuario. La app accede con la service_role key
-- guardada exclusivamente en Streamlit Secrets (lado servidor).

create table if not exists public.mca_state (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.mca_pdf_snapshots (
  id bigint generated by default as identity primary key,
  filename text not null,
  sha256 text not null,
  parsed jsonb not null,
  created_at timestamptz not null default now()
);

create unique index if not exists mca_pdf_snapshots_sha256_idx
  on public.mca_pdf_snapshots(sha256);

alter table public.mca_state enable row level security;
alter table public.mca_pdf_snapshots enable row level security;

